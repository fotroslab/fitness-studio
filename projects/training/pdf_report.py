"""PDF report builder for the Workout & Nutrition plan.

Uses fpdf2 with the built-in Helvetica family — deliberately ASCII-only so the
core font never hits a missing glyph (em-dashes and arrows are normalised).
Returns raw bytes ready for st.download_button.
"""

from __future__ import annotations

try:
    from fpdf import FPDF
    PDF_AVAILABLE = True
except ImportError:  # fpdf2 not installed — app must still work
    FPDF = object  # lets the class body below be defined; build_plan_pdf() refuses
    PDF_AVAILABLE = False

# Latin-1 safe replacement table for common typographic characters.
_SUBS = {
    "—": "-", "–": "-", "‘": "'", "’": "'", "“": '"', "”": '"',
    "→": "->", "≈": "~", "×": "x", "↑": "up", "↓": "down", "·": "-",
    "★": "*", "…": "...", " ": " ",
}

def _clean(text) -> str:
    s = str(text)
    for k, v in _SUBS.items():
        s = s.replace(k, v)
    return s.encode("latin-1", "replace").decode("latin-1")


class PlanPDF(FPDF):
    ACCENT = (94, 224, 181)
    PURPLE = (138, 180, 248)
    DARK = (10, 11, 16)
    PANEL = (24, 26, 38)
    TEXT = (40, 44, 60)

    def header(self):
        self.set_fill_color(*self.DARK)
        self.rect(0, 0, self.w, 18, "F")
        self.set_xy(12, 5)
        self.set_text_color(*self.ACCENT)
        self.set_font("Helvetica", "B", 13)
        self.cell(0, 8, _clean("GYM MEMBER  -  PERSONALIZED WORKOUT & NUTRITION PLAN"))
        self.set_text_color(200, 200, 210)
        self.set_font("Helvetica", "", 8)
        self.set_xy(12, 11)
        self.cell(0, 5, _clean("Generated by the Gym Member Recommender - Galaxy Series"))
        self.ln(14)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(*self.PURPLE)
        self.line(12, self.get_y(), self.w - 12, self.get_y())
        self.set_text_color(150, 152, 170)
        self.set_font("Helvetica", "I", 7.5)
        self.cell(0, 8, _clean(
            f"Page {self.page_no()}/{{nb}}  |  Not medical advice - consult your physician  |  "
            "Gym Member Segmentation & Recommender"), align="C")

    # --- building blocks -------------------------------------------------
    def section(self, title: str):
        self.ln(2)
        self.set_fill_color(*self.PANEL)
        self.set_text_color(0, 0, 0)
        self.set_font("Helvetica", "B", 12)
        self.cell(0, 9, _clean("  " + title), fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)
        self.set_text_color(*self.TEXT)

    def kv(self, key: str, value: str):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(90, 94, 120)
        self.cell(55, 5.5, _clean(key.upper()))
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*self.TEXT)
        self.cell(0, 5.5, _clean(value), new_x="LMARGIN", new_y="NEXT")

    def table(self, headers: list[str], rows: list[list[str]], widths: list[int]):
        self.set_font("Helvetica", "B", 8.5)
        self.set_fill_color(*self.DARK)
        self.set_text_color(*self.ACCENT)
        for h, w in zip(headers, widths):
            self.cell(w, 7, _clean(h), border=0, fill=True)
        self.ln()
        self.set_text_color(*self.TEXT)
        fill = False
        for row in rows:
            self.set_font("Helvetica", "", 8)
            self.set_fill_color(245, 246, 252) if fill else self.set_fill_color(255, 255, 255)
            for cell, w in zip(row, widths):
                self.cell(w, 6, _clean(cell), border=0, fill=True)
            self.ln()
            fill = not fill
        self.ln(2)


def build_plan_pdf(plan: dict) -> bytes:
    if not PDF_AVAILABLE:
        raise RuntimeError(
            "fpdf2 is not installed. Install it with:  pip install fpdf2  "
            "(the import module is 'fpdf') and restart the app.")
    p = plan["profile"]
    n = plan["nutrition"]
    m = plan["metrics"]
    mac = n["macros"]

    pdf = PlanPDF(orientation="P", unit="mm", format="A4")
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    # --- Persona summary --------------------------------------------------
    pdf.section("YOUR PERSONA")
    pdf.kv("Persona", plan["persona_name"])
    pdf.kv("Why", plan["persona_desc"])
    pdf.kv("Goal", f"{plan['goal_label']}  |  Focus: {plan['focus_label']}")
    pdf.kv("Training", f"{p.days} days/week, {p.session_minutes} min/session, experience level {p.experience}/3")
    pdf.kv("Diet", p.diet)

    # --- Body metrics -----------------------------------------------------
    pdf.section("BODY METRICS")
    pdf.kv("BMI", f"{m['bmi']}  ({m['bmi_cat']})")
    pdf.kv("Body fat", f"{m['body_fat']}%  ({m['fat_source']})")
    pdf.kv("Waist-to-hip", f"{m['whr']}  ({m['whr_cat']})")
    pdf.kv("Ideal weight range", f"{m['ideal_range'][0]} - {m['ideal_range'][1]} kg")
    pdf.kv("Max heart rate (est.)", f"{plan['hr_max']} bpm  |  Resting: {p.resting_hr or 'not provided (using %HRmax)'}")

    # --- HR zones ---------------------------------------------------------
    pdf.section("TARGET HEART-RATE ZONES")
    pdf.table(["Zone", "BPM range", "Use"],
              [[z["zone"], f"{z['lo']}-{z['hi']}", z["use"]] for z in plan["zones"]],
              [30, 28, 128])

    # --- Weekly workout plan ----------------------------------------------
    pdf.section("WEEKLY WORKOUT PLAN")
    for day in plan["week"]:
        pdf.ln(1)
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*PlanPDF.PURPLE)
        pdf.cell(0, 7, _clean(
            f"{day['weekday']}  -  {day['name']}  ({day['type']}, ~{day['est_calories']} kcal, {day['target_zone']})"),
            new_x="LMARGIN", new_y="NEXT")
        pdf.table(
            ["#", "Exercise", "Sets x Reps", "Rest", "Equipment"],
            [[str(i + 1), e["name"], e["sets_reps"], f"{e['rest_sec']}s", e["equipment"]]
             for i, e in enumerate(day["exercises"])],
            [8, 74, 30, 18, 40],
        )
        if day["finisher"]:
            pdf.set_font("Helvetica", "I", 8.5)
            pdf.set_text_color(*PlanPDF.TEXT)
            pdf.cell(0, 5, _clean(f"Finisher: {day['finisher']}"), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(110, 112, 135)
        pdf.multi_cell(0, 4.5, _clean("Cues: " + " | ".join(
            f"{e['name']}: {e['cue']}" for e in day["exercises"])), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(1)

    # --- Nutrition ---------------------------------------------------------
    pdf.section("NUTRITION TARGETS")
    pdf.kv("BMR (Mifflin-St Jeor)", f"{n['bmr']} kcal/day")
    pdf.kv("TDEE (activity-adjusted)", f"{n['tdee']} kcal/day")
    pdf.kv("Daily target", f"{n['target']} kcal/day")
    if n["comparison"]:
        pdf.kv("vs. your intake", f"{n['comparison']['known']} kcal (delta {n['comparison']['delta']:+d})")
    pdf.kv("Macros", f"Protein {mac['protein_g']} g ({mac['protein_pct']}%)  |  "
                     f"Carbs {mac['carbs_g']} g ({mac['carbs_pct']}%)  |  "
                     f"Fat {mac['fat_g']} g ({mac['fat_pct']}%)")
    pdf.kv("Water target", f"{n['water']} L/day (vs. your current {p.water_liters} L)")
    pdf.kv("Meal ideas", "; ".join(n["meal_ideas"][:4]))

    # --- Projection & recovery ---------------------------------------------
    pdf.section("WHAT 12 WEEKS COULD LOOK LIKE")
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*PlanPDF.ACCENT)
    pdf.cell(0, 7, _clean(plan["projection"]["headline"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*PlanPDF.TEXT)
    pdf.set_font("Helvetica", "", 8.5)
    pdf.multi_cell(0, 5, _clean(plan["projection"]["detail"]), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    pdf.section("RECOVERY PROTOCOL")
    for tip in plan["recovery"]["tips"]:
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(*PlanPDF.TEXT)
        pdf.multi_cell(0, 5, _clean(f"-  {tip}"), new_x="LMARGIN", new_y="NEXT")

    # --- Disclaimer ---------------------------------------------------------
    pdf.ln(4)
    pdf.set_draw_color(*PlanPDF.PURPLE)
    pdf.line(12, pdf.get_y(), pdf.w - 12, pdf.get_y())
    pdf.ln(2)
    from recommendation_engine import DISCLAIMER
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(130, 132, 150)
    pdf.multi_cell(0, 4.5, _clean(DISCLAIMER), new_x="LMARGIN", new_y="NEXT")

    out = pdf.output()
    return bytes(out)
